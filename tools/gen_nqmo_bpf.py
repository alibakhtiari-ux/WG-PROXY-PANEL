#!/usr/bin/env python3
"""Regenerate nqmo/collect/bpf.py — the fixed cBPF programs of the capture layer.

AF_PACKET SOCK_DGRAM filters run on data that starts at the IP header, so the
programs are compiled for DLT_RAW (link-type 101) — NOT with `tcpdump -i eth0`,
whose output carries 14-byte Ethernet offsets. We feed tcpdump an empty pcap
whose header declares LINKTYPE_RAW and ask for -dd.

  python3 tools/gen_nqmo_bpf.py            # rewrite nqmo/collect/bpf.py
  python3 tools/gen_nqmo_bpf.py --check    # exit 1 if the file is stale

The semantics of the committed bytecode are pinned independently by a cBPF
interpreter in tests/test_nqmo.py (NqmoBpfSemanticsTests) on crafted packets.
"""
import os
import re
import struct
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "nqmo", "collect", "bpf.py")
PORT = 53953

IP5 = "ip and (ip[0]&0x0f)=5"
PROGRAMS = (
    # name, snaplen, expression
    ("S1_HANDSHAKE", 44,
     IP5 + " and udp port %d and ip[6:2]&0x3fff=0 and ("
     "(udp[8]=1 and udp[4:2]=156) or (udp[8]=2 and udp[4:2]=100) or "
     "(udp[8]=3 and udp[4:2]=72) or "
     "(udp[8]=4 and udp[16:4]=0 and udp[20:4]=0))" % PORT),
    ("S2_FIRST_FRAG", 28,
     IP5 + " and ip[9]=17 and ip[6:2]&0x2000!=0 and ip[6:2]&0x1fff=0 "
     "and udp dst port %d" % PORT),
    ("S3_TAIL_FRAG", 20,
     IP5 + " and ip[9]=17 and ip[6:2]&0x1fff!=0"),
    ("S4_DATA", 44,
     IP5 + " and udp dst port %d and ip[6:2]&0x1fff=0 and udp[8]=4" % PORT),
    ("S5_SYN", 60,
     IP5 + " and ip[9]=6 and ip[6:2]&0x1fff=0 and tcp[13]&0x12=0x02"),
)

_LINE = re.compile(r"\{\s*(0x[0-9a-f]+),\s*(\d+),\s*(\d+),\s*(0x[0-9a-f]+)\s*\}")


def compile_expr(expr, snaplen, pcap):
    r = subprocess.run(["tcpdump", "-r", pcap, "-dd", expr],
                       capture_output=True, text=True, check=True)
    prog = [(int(a, 16), int(b), int(c), int(d, 16))
            for a, b, c, d in _LINE.findall(r.stdout)]
    if not prog:
        raise SystemExit("tcpdump produced no program for: " + expr)
    # The accept return carries the capture length (65535 from -dd); replace it
    # with the stream's hard snaplen so payload never leaves the kernel.
    fixed = []
    for code, jt, jf, k in prog:
        if code == 0x06 and k != 0:
            k = snaplen
        fixed.append((code, jt, jf, k))
    return fixed


def render(compiled):
    out = ['"""GENERATED by tools/gen_nqmo_bpf.py — do not edit by hand.',
           "",
           "Fixed cBPF programs for AF_PACKET SOCK_DGRAM sockets (DLT_RAW offsets:",
           "byte 0 is the IPv4 header). Every accept returns the stream's hard",
           "snaplen. Port %d is baked in; capture refuses to start on any other" % PORT,
           'listen_port instead of patching bytecode at runtime."""',
           "",
           "PORT = %d" % PORT,
           "",
           "PROGRAMS = {"]
    for name, snap, expr, prog in compiled:
        out.append("    %r: {" % name)
        out.append("        \"snaplen\": %d," % snap)
        out.append("        \"expr\": %r," % expr)
        out.append("        \"insns\": (")
        for ins in prog:
            out.append("            (0x%02x, %d, %d, 0x%08x)," % ins)
        out.append("        ),")
        out.append("    },")
    out.append("}")
    out.append("")
    return "\n".join(out)


def build():
    with tempfile.TemporaryDirectory() as d:
        pcap = os.path.join(d, "raw.pcap")
        with open(pcap, "wb") as f:
            # pcap global header: magic, v2.4, tz 0, sigfigs 0, snaplen, LINKTYPE_RAW
            f.write(struct.pack("<IHHiIII", 0xA1B2C3D4, 2, 4, 0, 0, 65535, 101))
        compiled = [(n, s, e, compile_expr(e, s, pcap)) for n, s, e in PROGRAMS]
    return render(compiled)


def main():
    text = build()
    if "--check" in sys.argv:
        with open(OUT, encoding="utf-8") as f:
            cur = f.read()
        if cur != text:
            print("nqmo/collect/bpf.py is stale; run tools/gen_nqmo_bpf.py")
            return 1
        print("bpf.py up to date")
        return 0
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote", os.path.relpath(OUT, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
